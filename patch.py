def main():
    if not ROOT.is_dir():
        sys.exit(f"not a directory: {ROOT}")
    cover = ROOT / "cover.py"
    if not cover.exists() or cover.read_text(encoding="utf-8") != COVER_PY:
        cover.write_text(COVER_PY, encoding="utf-8")
        REPORT.append(("cover.py", "created/updated", "ok"))
    else:
        REPORT.append(("cover.py", "created/updated", "already"))
    patch_main()
    patch_pages()
    patch_misc()

    width = max(len(r[1]) for r in REPORT)
    for name, label, status in REPORT:
        mark = {"ok": "+", "already": "=", "skip": "-", "MISSING": "!", "NO FILE": "!"}.get(status.split()[0], "+")
        print(f" {mark} {name:<18} {label:<{width}}  {status}")
    print("\nProtocol codenames (keep private):")
    for k, v in CODES.items():
        print(f"   {v:<8} = {k}")
    if MISSING:
        print(f"\n{MISSING} anchor(s) not found: those files differ from what the patch expects (see '!').")
        sys.exit(1)
    print("\nDone. Delete the *.bak files before deploying.")


if __name__ == "__main__":
    main()
