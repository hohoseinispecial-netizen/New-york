# panel-only URLs: they exist only under the secret panel prefix, everywhere else -> 404
_PANEL_EXACT = {"/login", "/dashboard", "/test-ws", "/stats", "/sub-all"}


def _panel_only(path: str) -> bool:
    if path in _PANEL_EXACT or path == "/api" or path.startswith("/proxy"):
        return True
    return path.startswith("/api/") and not path.startswith("/api/public/")


class PanelGate:
    """Pure ASGI middleware: <panel_path>/x -> /x ; panel-only URLs without the prefix -> 404."""

    def __init__(self, app, panel_path: str):
        self.app = app
        self.pp = panel_path.rstrip("/")

    async def __call__(self, scope, receive, send):
        if scope["type"] == "http":
            path = scope["path"]
            if path == self.pp or path.startswith(self.pp + "/"):
                inner = path[len(self.pp):] or "/"
                if inner == "/":
                    inner = "/dashboard"
                scope = dict(scope)
                scope["path"] = inner
                scope["raw_path"] = inner.encode()
            elif _panel_only(path):
                await HTMLResponse(NOT_FOUND_HTML, status_code=404)(scope, receive, send)
                return
        await self.app(scope, receive, send)


def install_cover(app, panel_path: str):
    app.add_middleware(PanelGate, panel_path=panel_path)

    async def _http_exc(request, exc):
        p = request.url.path
        if exc.status_code in (403, 404, 405) and (not p.startswith("/api/") or p.startswith("/api/public/")):
            return HTMLResponse(NOT_FOUND_HTML, status_code=404)
        return JSONResponse({"detail": exc.detail}, status_code=exc.status_code,
                            headers=getattr(exc, "headers", None))

    async def _val_exc(request, exc):
        if request.url.path.startswith("/api/") and not request.url.path.startswith("/api/public/"):
            return JSONResponse({"detail": "bad request"}, status_code=400)
        return HTMLResponse(NOT_FOUND_HTML, status_code=404)

    app.add_exception_handler(StarletteHTTPException, _http_exc)
    app.add_exception_handler(RequestValidationError, _val_exc)
