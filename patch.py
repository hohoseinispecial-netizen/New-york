"""
patch.py — hardening / cover patch for the panel project.

Usage (from anywhere):   python patch.py [project_dir]      (default: current dir)

What it does
  * main.py   : hidden panel path, landing page on "/", generic 404, no /health data,
                /proxy behind login, no default password, no server banner,
                neutral tunnel paths, brand "New York", fixes the circular import.
  * cover.py  : (new) landing page + generic 404 + hidden-panel gate middleware.
  * pages.py  : brand -> "New York", protocol names -> codenames, default-password hint
                removed, all panel URLs moved under the hidden panel path.
  * smart.py / telegram_bot.py : protocol names -> codenames.
  * xray_core.py / extra_protocols.py / xhttp_siz10.py : neutral paths / service names.
  * Dockerfile: uvicorn start command without Server header.

Safe to run twice (idempotent). Every changed file is backed up once as <file>.bak
(delete the .bak files before deploying). A report is printed at the end.
"""
import re
