from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
REPORT = []          # (file, label, status)
MISSING = 0


class F:
    def __init__(self, name):
        self.name = name
        self.path = ROOT / name
        self.ok = self.path.exists()
        self.text = self.path.read_text(encoding="utf-8") if self.ok else ""
        self.orig = self.text

    def _log(self, label, status):
        global MISSING
        if status == "MISSING":
            MISSING += 1
        REPORT.append((self.name, label, status))

    def rep(self, old, new, label, count=None, optional=False):
        if not self.ok:
            return self._log(label, "NO FILE")
        if old in self.text:
            self.text = self.text.replace(old, new) if count is None else self.text.replace(old, new, count)
            self._log(label, "ok")
        elif new in self.text:
            self._log(label, "already")
        else:
            self._log(label, "skip (not present)" if optional else "MISSING")

    def sub(self, pattern, repl, label, flags=0, marker=None, absent=None, optional=False):
        """regex substitution; `marker` (text that exists only after patching) or `absent`
        (text that disappears after patching) make it idempotent."""
        if not self.ok:
            return self._log(label, "NO FILE")
        if (marker and marker in self.text) or (absent and absent not in self.text):
            return self._log(label, "already")
        new, n = re.subn(pattern, repl, self.text, flags=flags)
        if n:
            self.text = new
            self._log(label, f"ok x{n}")
        else:
            self._log(label, "skip (not present)" if optional else "MISSING")

    def save(self):
        if self.ok and self.text != self.orig:
            bak = self.path.with_name(self.path.name + ".bak")
            if not bak.exists():
                bak.write_text(self.orig, encoding="utf-8")
            self.path.write_text(self.text, encoding="utf-8")


